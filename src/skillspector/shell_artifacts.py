"""Bounded, immutable provenance for files a shell program constructs.

This is a model of inspected native copy/archive operations, not a filesystem.
Callers must establish command identity, argument values, successful operation
and execution order. An unknown write invalidates the affected namespace. No
sample command, compressor, archive member or generated program is executed.
"""

from __future__ import annotations

import posixpath
from collections.abc import Callable
from dataclasses import dataclass

from skillspector.shell_sources import ShellSourceValue

MAX_GENERATED_FILES = 256
MAX_GENERATED_BYTES = 1_000_000
MAX_GENERATED_DEPTH = 8


def _path(value: str, *, member: bool = False) -> str | None:
    if not value or any(character in value for character in ("\\", "\x00", ":")):
        return None
    if member and value.startswith("/"):
        return None
    pieces = value.removeprefix("/").split("/")
    if any(piece in {"", ".", ".."} for piece in pieces):
        return None
    normalized = posixpath.normpath(value)
    if normalized in {".", "..", "/"} or normalized.startswith("../"):
        return None
    return normalized


@dataclass(frozen=True, slots=True)
class ShellArtifact:
    """Exact text, an archive inventory, or bounded data unavailable as source.

    Opaque data contributes its byte count to limits but never supplies text to
    a cat/source reconstruction. It can occupy a known archive member without
    inventing its contents, such as a manifest whose order depends on locale.
    """

    value: ShellSourceValue | None = None
    members: tuple[tuple[str, ShellArtifact], ...] = ()
    opaque_size: int | None = None
    executable: bool | None = None
    directories: tuple[str, ...] = ()

    @property
    def is_archive(self) -> bool:
        return self.value is None and self.opaque_size is None


class ShellArtifactStore:
    """A finite snapshot of generated bytes, isolated from the host filesystem.

    A directory can be archived only after its namespace was explicitly created
    empty and every subsequent write was accounted for. Cached input directories
    are deliberately not considered empty or exclusively owned by this model.
    Failed/unsupported operations never leave a previously trusted destination.
    """

    def __init__(self, check_runtime: Callable[[], None]) -> None:
        self._check_runtime = check_runtime
        self._files: dict[str, ShellArtifact] = {}
        self._owned: set[str] = set()
        self._owned_files: set[str] = set()
        self._unknown: set[str] = set()
        self._decimal_domains: set[tuple[str, str]] = set()
        self._bytes = 0
        self.complete = True
        self._parent: ShellArtifactStore | None = None
        self._revision = 0
        self._parent_revision = 0

    def effect_snapshot(self) -> tuple[object, ...]:
        """Capture immutable facts used by later reads, lookup, and writes.

        Repeated invalidations may increment the transactional revision without
        changing these facts. Loop convergence must compare semantic state.
        """
        self._check_runtime()
        return (
            tuple(sorted(self._files.items())),
            frozenset(self._owned),
            frozenset(self._owned_files),
            frozenset(self._unknown),
            frozenset(self._decimal_domains),
            self.complete,
        )

    def fork(self) -> ShellArtifactStore:
        """Try an optional producer proof without changing the accepted snapshot."""
        self._check_runtime()
        child = ShellArtifactStore(self._check_runtime)
        child._files = self._files.copy()
        child._owned = self._owned.copy()
        child._owned_files = self._owned_files.copy()
        child._unknown = self._unknown.copy()
        child._decimal_domains = self._decimal_domains.copy()
        child._bytes = self._bytes
        child.complete = self.complete
        child._parent = self
        child._parent_revision = self._revision
        return child

    def adopt(self, child: ShellArtifactStore) -> bool:
        """Commit only a successful direct fork; artifacts themselves are immutable."""
        self._check_runtime()
        if (
            child._parent is not self
            or child._parent_revision != self._revision
            or not child.complete
        ):
            return False
        self._files = child._files.copy()
        self._owned = child._owned.copy()
        self._owned_files = child._owned_files.copy()
        self._unknown = child._unknown.copy()
        self._decimal_domains = child._decimal_domains.copy()
        self._bytes = child._bytes
        self._revision += 1
        child._parent = None
        return True

    def _size(self, artifact: ShellArtifact) -> int | None:
        """Validate the entire inventory under one shared node/byte allowance."""
        total = 0
        visited = 0
        pending = [(artifact, 0)]
        while pending:
            self._check_runtime()
            current, depth = pending.pop()
            visited += 1
            if current.executable is not None and not isinstance(current.executable, bool):
                return None
            if depth > MAX_GENERATED_DEPTH or visited > MAX_GENERATED_FILES:
                return None
            if current.opaque_size is not None:
                if (
                    current.value is not None
                    or current.members
                    or current.directories
                    or not 0 <= current.opaque_size <= MAX_GENERATED_BYTES
                ):
                    return None
                total += current.opaque_size
            elif current.value is not None:
                if current.members or current.directories:
                    return None
                total += len(current.value.text.encode("utf-8"))
            else:
                directories: set[str] = set()
                for directory in current.directories:
                    self._check_runtime()
                    visited += 1
                    if (
                        _path(directory, member=True) != directory
                        or directory in directories
                        or depth + 1 > MAX_GENERATED_DEPTH
                        or visited + len(pending) > MAX_GENERATED_FILES
                    ):
                        return None
                    directories.add(directory)
                names: set[str] = set()
                for name, child in current.members:
                    self._check_runtime()
                    if (
                        _path(name, member=True) != name
                        or any(self._within(directory, name) for directory in directories)
                        or any(
                            self._within(name, other) or self._within(other, name)
                            for other in names
                        )
                        or visited + len(pending) >= MAX_GENERATED_FILES
                    ):
                        return None
                    names.add(name)
                    pending.append((child, depth + 1))
            if total > MAX_GENERATED_BYTES:
                return None
        return total

    @staticmethod
    def _within(path: str, parent: str) -> bool:
        return path == parent or path.startswith(parent.rstrip("/") + "/")

    def _decimal_unknown(self, path: str, *, namespace: bool = False) -> bool:
        for prefix, suffix in self._decimal_domains:
            candidate = path
            while candidate:
                self._check_runtime()
                if candidate.startswith(prefix) and candidate.endswith(suffix):
                    end = len(candidate) - len(suffix)
                    digits = candidate[len(prefix) : end] if end >= len(prefix) else ""
                    if digits and digits.isascii() and digits.isdecimal():
                        return True
                parent = posixpath.dirname(candidate)
                if parent == candidate:
                    break
                candidate = parent
            if namespace and (prefix.startswith(path.rstrip("/") + "/") or path.startswith(prefix)):
                # A complete directory inventory requires every possible
                # descendant to be known; prefix overlap is conservative.
                return True
        return False

    def invalidate_decimal_path(self, prefix: str, suffix: str) -> bool:
        """Forget all names in one fixed-prefix/decimal/fixed-suffix domain.

        A process id supplies a bounded path domain, never fresh ownership or
        exact filename bytes. Existing numeric aliases and later reads share
        this invalidation; unrelated fresh trees retain their facts.
        """
        self._check_runtime()
        if (
            len(prefix) + len(suffix) > 4096
            or _path(prefix + "0" + suffix) != prefix + "0" + suffix
        ):
            self.invalidate(None)
            return False
        self._decimal_domains.add((prefix, suffix))
        self._revision += 1
        if len(self._decimal_domains) + len(self._unknown) > MAX_GENERATED_FILES:
            self.invalidate(None)
            return False
        for path in tuple(self._files):
            if self._decimal_unknown(path):
                size = self._size(self._files.pop(path))
                self._owned_files.discard(path)
                self._bytes -= size or 0
        return True

    def create_empty_directory(self, path: str) -> bool:
        """Record a proven fresh directory, such as a successful mktemp -d."""
        self._check_runtime()
        key = _path(path)
        if (
            key is None
            or key in self._owned
            or any(self._within(item, key) or self._within(key, item) for item in self._files)
        ):
            return False
        if any(self._within(key, item) or self._within(item, key) for item in self._unknown):
            return False
        if self._decimal_unknown(key, namespace=True):
            return False
        if len(self._owned) >= MAX_GENERATED_FILES:
            self.complete = False
            return False
        self._owned.add(key)
        self._revision += 1
        return True

    def create_empty_file(self, path: str, value: ShellSourceValue) -> bool:
        """Record a proven fresh regular file without owning its parent tree."""
        self._check_runtime()
        key = _path(path)
        if (
            key is None
            or value.kind != "code"
            or value.text
            or any(self._within(item, key) or self._within(key, item) for item in self._files)
            or any(self._within(item, key) for item in self._owned)
            or any(self._within(item, key) or self._within(key, item) for item in self._unknown)
            or self._decimal_unknown(key, namespace=True)
        ):
            return False
        if not self.write(key, ShellArtifact(value, executable=False)):
            return False
        self._owned_files.add(key)
        self._revision += 1
        return True

    def invalidate(self, path: str | None) -> None:
        """Forget known bytes after an unknown write, alias or directory escape."""
        self._check_runtime()
        self._revision += 1
        key = _path(path) if path is not None else None
        if key is None:
            self._files.clear()
            self._owned.clear()
            self._owned_files.clear()
            self._decimal_domains.clear()
            self._bytes = 0
            self.complete = False
            return
        self._unknown.add(key)
        if len(self._unknown) + len(self._decimal_domains) > MAX_GENERATED_FILES:
            self.invalidate(None)
            return
        for candidate in tuple(self._files):
            if self._within(candidate, key):
                artifact = self._files.pop(candidate)
                self._owned_files.discard(candidate)
                size = self._size(artifact)
                self._bytes -= size or 0

    def read(self, path: str) -> ShellArtifact | None:
        self._check_runtime()
        key = _path(path)
        if key is None or not self.complete:
            return None
        if any(self._within(key, item) for item in self._unknown) or self._decimal_unknown(key):
            return None
        return self._files.get(key)

    def exists(self, path: str) -> bool | None:
        """Distinguish known absence in an owned tree from missing evidence."""
        self._check_runtime()
        key = _path(path)
        if (
            key is None
            or not self.complete
            or any(self._within(key, item) or self._within(item, key) for item in self._unknown)
            or self._decimal_unknown(key, namespace=True)
        ):
            return None
        if (
            key in self._files
            or key in self._owned
            or any(self._within(item, key) for item in (*self._files, *self._owned))
        ):
            return True
        return False if any(self._within(key, item) for item in self._owned) else None

    def write(self, path: str, artifact: ShellArtifact) -> bool:
        """Record exact, successfully replaced bytes; reject aliases upstream."""
        self._check_runtime()
        key = _path(path)
        size = self._size(artifact)
        if key is None or size is None or not self.complete:
            self.invalidate(path)
            return False
        if any(self._within(key, item) for item in self._unknown) or self._decimal_unknown(key):
            return False
        if any(
            other != key and (self._within(key, other) or self._within(other, key))
            for other in self._files
        ) or any(self._within(directory, key) for directory in self._owned):
            # Native files cannot simultaneously be directory ancestors.
            # Refuse the whole snapshot instead of publishing a fictitious tree.
            self.invalidate(None)
            return False
        previous = self._files.get(key)
        previous_size = self._size(previous) if previous is not None else 0
        if (
            previous_size is None
            or len(self._files) + int(previous is None) > MAX_GENERATED_FILES
            or self._bytes - previous_size + size > MAX_GENERATED_BYTES
        ):
            self.invalidate(path)
            self.complete = False
            return False
        self._files[key] = artifact
        self._bytes = self._bytes - previous_size + size
        self._revision += 1
        return True

    def copy(self, source: str, destination: str) -> bool:
        artifact = self.read(source)
        if artifact is None:
            self.invalidate(destination)
            return False
        return self.write(destination, artifact)

    def archive(self, root: str, destination: str, *, member_prefix: str = "") -> bool:
        """Model tar creation from one known file or exclusively owned tree."""
        self._check_runtime()
        key = _path(root)
        target = _path(destination)
        if (
            key is None
            or target is None
            or member_prefix
            and _path(member_prefix, member=True) != member_prefix
            or self._within(target, key)
            or not any(self._within(key, item) for item in self._owned)
            or any(self._within(item, key) or self._within(key, item) for item in self._unknown)
            or self._decimal_unknown(key, namespace=True)
        ):
            self.invalidate(destination)
            return False
        artifact = self.read(key)
        directories = () if artifact is not None else self.directory_inventory(key)
        if directories is None:
            self.invalidate(destination)
            return False
        if artifact is None and member_prefix:
            directories = (member_prefix, *(member_prefix + "/" + name for name in directories))
        members = (
            ((member_prefix or posixpath.basename(key), artifact),)
            if artifact is not None
            else tuple(
                ((member_prefix + "/" if member_prefix else "") + path[len(key) + 1 :], item)
                for path, item in sorted(self._files.items())
                if path.startswith(key + "/")
            )
        )
        if any(_path(name, member=True) != name for name, _ in members):
            self.invalidate(destination)
            return False
        return self.write(destination, ShellArtifact(members=members, directories=directories))

    def inventory(self, root: str) -> tuple[tuple[str, ShellArtifact], ...] | None:
        """Expose a complete owned tree for finite find/hash operations."""
        self._check_runtime()
        key = _path(root)
        if (
            key is None
            or not self.complete
            or not any(self._within(key, item) for item in self._owned)
            or any(self._within(item, key) or self._within(key, item) for item in self._unknown)
            or self._decimal_unknown(key, namespace=True)
        ):
            return None
        return tuple(
            (path[len(key) + 1 :], artifact)
            for path, artifact in sorted(self._files.items())
            if path.startswith(key + "/")
        )

    def directory_inventory(self, root: str) -> tuple[str, ...] | None:
        """Retain explicit empty descendants alongside the regular-file inventory."""
        if (
            self.inventory(root) is None
            or self.exists(root) is not True
            or self.read(root) is not None
        ):
            return None
        return tuple(
            path[len(root) + 1 :] for path in sorted(self._owned) if path.startswith(root + "/")
        )

    def owns(self, path: str) -> bool:
        """Prove an exact fresh file or a path inside a fresh tree is owned.

        Unlike inventory(), this does not claim all descendants are known. An
        unknown path ancestor still refuses ownership because it may be an alias.
        """
        self._check_runtime()
        key = _path(path)
        return bool(
            key is not None
            and self.complete
            and (
                key in self._owned_files or any(self._within(key, parent) for parent in self._owned)
            )
            and not any(self._within(key, unknown) for unknown in self._unknown)
            and not self._decimal_unknown(key)
            and not any(key != name and self._within(key, name) for name in self._files)
        )

    def extract(self, source: str, destination: str) -> bool:
        """Model extraction only into a proven fresh, exclusively owned tree."""
        self._check_runtime()
        artifact = self.read(source)
        root = _path(destination)
        if (
            artifact is None
            or not artifact.is_archive
            or root is None
            or not any(self._within(root, item) for item in self._owned)
            or any(self._within(path, root) for path in self._files)
            or any(self._within(path, root) or self._within(root, path) for path in self._unknown)
            or self._decimal_unknown(root, namespace=True)
        ):
            self.invalidate(destination)
            return False
        for directory in artifact.directories:
            path = root + "/" + directory
            if self.exists(path) is not True and not self.create_empty_directory(path):
                self.invalidate(destination)
                return False
        names: set[str] = set()
        for name, child in artifact.members:
            self._check_runtime()
            if _path(name, member=True) != name or name in names:
                self.invalidate(destination)
                return False
            names.add(name)
            if not self.write(root + "/" + name, child):
                self.invalidate(destination)
                return False
        return True
